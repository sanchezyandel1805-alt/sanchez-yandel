# Podría ser un caso de phishing, porque intenta engañar al estudiante para robar su contraseña.
# b. ¿Qué debería hacer el estudiante?
# No debe abrir el enlace ni ingresar sus datos. Lo mejor es eliminar el correo y verificar su cuenta desde la página oficial de Google.
# c. ¿Qué podría suceder si ingresa sus datos?
# Los delincuentes podrían robar su contraseña, entrar a su cuenta y acceder a su información personal.

# Situación 2: La contraseña compartida
# a. ¿Qué errores de seguridad está cometiendo?
# Está usando la misma contraseña para varias cuentas y además la comparte con otra persona. Esto pone en riesgo su información.
# b. ¿Qué consecuencias podría tener?
# Si alguien descubre su contraseña, podría entrar a todas sus cuentas, robar información o hacerse pasar por él.
# c. ¿Qué medidas debería implementar?
# Debe utilizar contraseñas diferentes y seguras para cada cuenta, no compartirlas con nadie y activar la verificación en dos pasos.

# Situación 3: Archivos bloqueados
# a. ¿Qué tipo de amenaza podría ser?
# Podría tratarse de un ransomware, un programa malicioso que bloquea los archivos y pide dinero para recuperarlos.
# b. ¿Qué daños podría provocar?
# Podría provocar la pérdida de archivos importantes, el robo de información y daños en la computadora.
# c. ¿Qué medidas permitirían prevenir esta situación?
# Mantener el antivirus actualizado, no descargar archivos sospechosos, evitar enlaces desconocidos y realizar copias de seguridad periódicamente.